-- Bundles spelldrawer.lua and its modules into one file: dist/evade_v<version>.lua
-- Each module becomes a package.preload entry, so every require() works unchanged.
-- Run from the repo root: lua bundler.lua
-- Ship the .lua: Umbrella runs a custom Lua (_VERSION "Lua 6.6", string.dump blocked) that rejects stock luac bytecode
-- bump for each release; rebuilding the same version overwrites its file
local VERSION = "1.0.0"
local ENTRY, OUT = "spelldrawer.lua", "dist/evade_v" .. VERSION .. ".lua"

local function read(path)
    local f = assert(io.open(path, "rb"))
    local s = f:read("a")
    f:close()
    return s
end

local entry = read(ENTRY)
-- the module list lives in the entry's MODULES table, so a new module only needs adding there
local list = assert(entry:match("local MODULES = (%b{})"), "no MODULES table in " .. ENTRY)
local parts = { "-- generated by bundler.lua from " .. ENTRY .. "; edit the source files, not this one\n" }
for name in list:gmatch('"([%w_]+)"') do
    local src = read(name .. ".lua")
    assert(load(src, "@" .. name .. ".lua"), "syntax error in " .. name .. ".lua")
    -- the newline before `end` keeps a trailing comment from swallowing it
    parts[#parts + 1] = ("package.preload[%q] = function(...)\n%s\nend\n"):format(name, src)
end
parts[#parts + 1] = entry
local out = table.concat(parts)
assert(load(out, "@" .. OUT), "bundle does not compile")

os.execute(package.config:sub(1, 1) == "\\" and "if not exist dist mkdir dist" or "mkdir -p dist")
local f = assert(io.open(OUT, "wb"))
f:write(out)
f:close()
print(("wrote %s (%d modules + entry, %d bytes)"):format(OUT, #parts - 2, #out))
